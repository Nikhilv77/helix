public class J08 {
    public static void main(String[] args) {
        char letter = 'a';
        System.out.println(letter + 1);
        System.out.println((char) (letter + 1));
        System.out.println("" + letter + 1);
        System.out.println('a' + 'b');
        System.out.println("sum: " + 1 + 2);
        System.out.println("sum: " + (1 + 2));
    }
}
